"use client";

import React, { use } from "react";
import { useParams } from "next/navigation";
import ReferralSummaryCard from "@/components/referrals/single/referral-summary-card";
import ReferralUserCard from "@/components/referrals/single/referral-user-card";
import ReferralProviderCard from "@/components/referrals/single/referral-provider-card";
import ReferralHistoryTimeline from "@/components/referrals/single/referral-history-timeline";
import { mockReferralsList } from "@/components/referrals/referrals-table";

export default function SingleReferralPage({
  params,
}: {
  params?: Promise<{ id: string }> | { id: string };
}) {
  const unwrappedParams = params
    ? typeof (params as any).then === "function"
      ? use(params as Promise<{ id: string }>)
      : (params as { id: string })
    : null;
  const routeParams = useParams();
  const id = unwrappedParams?.id || (routeParams?.id as string) || "1";

  const referral =
    mockReferralsList.find((r) => r.id === id || r.code === id) ||
    mockReferralsList[0];

  const events = [
    {
      id: "1",
      title: `Provider Selected by ${referral.user}`,
      timestamp: "Apr 12, 2023 | 09:32AM",
    },
    {
      id: "2",
      title: `Referral code Generated by ${referral.user}`,
      timestamp: `${referral.generationDate} | 09:32AM`,
    },
    {
      id: "3",
      title: `Referral Code redeemed by ${referral.provider}`,
      timestamp: `${referral.redemptionDate} | 09:32AM`,
    },
  ];

  return (
    <div className="w-full max-w-[1400px] mx-auto pb-16 font-sans select-none">
      {/* 1. Referral Top Summary Card */}
      <ReferralSummaryCard
        code={referral.code}
        generatedDate={referral.generationDate}
        status={referral.status}
      />

      {/* 2. Side-by-Side User & Provider Cards */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6 mb-6">
        <ReferralUserCard
          userId={`USR-${referral.id || "1075"}`}
          name={referral.user}
          location="Chelsea, London"
          rating="5.0"
          joinedDate="Oct 2, 2026"
          lastActiveDate="Oct 2, 2026, 10:00AM"
          avatarUrl="/jane-doe-avatar.jpg"
        />

        <ReferralProviderCard
          providerId="PRV-0091"
          name={referral.provider}
          location="Ikeja, Lagos"
          initials={referral.providerInitials}
          onboardingDate="October 10, 2026"
        />
      </div>

      {/* 3. History Timeline */}
      <ReferralHistoryTimeline events={events} />
    </div>
  );
}
